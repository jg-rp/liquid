def generate() -> str:
    constants: list[str] = []
    names: list[str] = []
    literals: list[str] = []
    mapping: list[str] = []

    for id, (name, description) in enumerate(TOKEN_DEFINITIONS.items(), 1):
        constant = f"TOKEN_{name}"

        constants.append(f"{constant}: Literal[{id}] = {id}")
        names.append(f"    {constant!r}: {description!r}")
        literals.append(f"    {id}")
        mapping.append(f"    {constant}: {constant!r}")

    return f"""\
# DO NOT EDIT -- generated by generate_tokens.py

from typing import Literal

__all__ = (
{",\n".join(f'    "TOKEN_{name}"' for name in TOKEN_DEFINITIONS)},
)

type TokenKind = Literal[\n{",\n".join(literals)},\n]

type Token = tuple[TokenKind, int, int]
\"\"\"Token type, start index and end index.\"\"\"

{chr(10).join(constants)}

TOKEN_NAMES = (
    None,
{chr(10).join(f"    {description!r}," for description in TOKEN_DEFINITIONS.values())}
)

TOKEN_MAP = {{
{",\n".join(mapping)},
}}


def token_value(token: Token, source: str) -> str:
    \"\"\"Return the substring in source spanned by token.\"\"\"
    return source[token[1] : token[2]]


def span(start: Token, stop: Token) -> Token:
    \"\"\"Return a new token spanning start and stop.\"\"\"
    return (TOKEN_SPAN, start[1], stop[2])
"""


if __name__ == "__main__":
    print(generate())
